    private void jMenuItem2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem2ActionPerformed
        // TODO add your handling code here:
        try
        {
            //casting
            String movieName = (String)txtComboBoxNames.getSelectedItem();
            
            //converting to integer
            
            double mattressPrice = Double.parseDouble(txtPrice.getText());
            
            
            
            final double VAT_RATE = 0.15;
            
            //calculations
            double subTotal = (5/100) * mattressPrice;
            double vatAmt = subTotal * VAT_RATE;
            double totalPrice = subTotal + vatAmt;
            
            txtReportArea.setText(
            
                         "customer Name " + txtName + "\n" +
                         "Product " + txtComboBoxNames + "\n"+
                         "TICKET PRICE: R " + txtPrice + "\n" +
                         "TOTAL PRICE: R " + totalPrice);
            //saving into txt file
            try
            {
                FileWriter writer = new FileWriter("report.txt");
                writer.write(txtReportArea.getText());
                writer.close();
                
                JOptionPane.showMessageDialog(this,
                        "Record saved successfully to report.txt");
                
                
            }
            catch(IOException e )
            {
               JOptionPane.showMessageDialog(this,"Error, saving file"+ e.getMessage());
            }
            
        }
        catch(NumberFormatException e)
         {
             JOptionPane.showMessageDialog(this,
                        "Price can not be zero");
                    
          }
    }//GEN-LAST:event_jMenuItem2ActionPerformed

